"""S615: regenerate native causal training features at 128/256/512 hops.

Prerequisite: original S613 development audio cache + labels, generated by
scripts.s613_prepare_strict_live --phase development with original protocol.

Read ONLY train/dev sources, never the test split. The new feature artifacts
are isolated under root/multihop/, with independent source and hop hashes.
The original S613 audio/features/labels are not altered.

Example:
 python -m scripts.s615_prepare_multihop --root data/S613 --hops 128 256 512
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np

from causal_note.strict_live import HOP, SCHEMA, SR, feature_track


VALID_HOPS = (128, 256, 512)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def prepare_one(root, spec, hop):
    if spec["split"] not in ("train", "dev"):
        raise ValueError("S615 preparation must never access test audio/labels")
    origin = root / "cache" / spec["id"]
    meta_path = origin.with_suffix(".json")
    audio_path = origin.with_suffix(".audio.npy")
    if not (audio_path.exists() and meta_path.exists()):
        raise FileNotFoundError(f"Prepare S613 development sources first: {spec['name']}")
    info = json.loads(meta_path.read_text(encoding="utf-8"))
    if (info.get("source", {}).get("id") != spec["id"] or
            info.get("source", {}).get("split") != spec["split"] or
            info.get("annotations_read") is not True or
            "labels" not in info):
        raise ValueError(f"Missing / inconsistent development provenance: {spec['name']}")
    # Reuse the original resampled audio, not any test audio or future audio.
    audio = np.load(audio_path, allow_pickle=False)
    if audio.ndim != 1 or audio.dtype != np.float32:
        raise ValueError("S613 cached audio must be mono float32")
    target_dir = root / "multihop" / f"hop{hop}"
    target_dir.mkdir(parents=True, exist_ok=True)
    target = target_dir / (spec["id"] + ".npz")
    proof = target.with_suffix(".json")
    audio_sha = sha(audio.tobytes())
    if target.exists() or proof.exists():
        if not (target.exists() and proof.exists()):
            raise ValueError("Incomplete multihop cache; preserve for audit: " + str(target))
        old = json.loads(proof.read_text(encoding="utf-8"))
        if (old.get("audio_sha256") != audio_sha or old.get("hop") != hop or
                old.get("source_id") != spec["id"]):
            raise ValueError("Multihop cache provenance mismatch: " + str(target))
        return dict(source=spec["name"], hop=hop, reused=True)
    ends, features = feature_track(audio, block_size=2048, hop=hop)
    # The native feature ABI must not depend on hop. Absolutely no label,
    # time target or MIDI event enters this feature extraction.
    if features.shape[1:] != (49, 110) or len(ends) != len(audio) // hop:
        raise AssertionError(f"Unexpected NOTE feature ABI at hop={hop}: {features.shape}")
    np.savez_compressed(target, ends=ends, features=features)
    receipt = dict(
        source_id=spec["id"], source_name=spec["name"],
        split=spec["split"], composition=spec["composition"],
        corpus=spec["corpus"], hop=hop,
        input_sample_rate=SR, input_samples=len(audio),
        audio_sha256=audio_sha,
        original_annotation_sha256=info["labels"]["sha256"],
        original_feature_schema=SCHEMA,
        feature_shape=list(features.shape),
        feature_sha256=sha(features.tobytes()),
        lookahead_samples=0,
        labels_not_used_to_make_features=True,
    )
    proof.write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n",
                     encoding="utf-8")
    return dict(source=spec["name"], hop=hop, frames=len(ends), reused=False)


def prepare(root, hops=VALID_HOPS, *, source_limit=None,
            pilot_train_sources=None, pilot_dev_sources=None):
    protocol = json.loads((root / "protocol.json").read_text(encoding="utf-8"))
    if protocol.get("schema") != SCHEMA or protocol.get("sample_rate") != SR:
        raise ValueError("S613 protocol schema/sample rate mismatch")
    if not hops or any(h not in VALID_HOPS for h in hops):
        raise ValueError("Valid hops are 128, 256, 512")
    sources = [s for s in protocol["sources"] if s["split"] in ("train", "dev")]
    if pilot_train_sources is not None or pilot_dev_sources is not None:
        if not pilot_train_sources or not pilot_dev_sources:
            raise ValueError("Pilot needs positive train AND dev source limits")
        sources = ([s for s in sources if s["split"] == "train"][:pilot_train_sources]
                   + [s for s in sources if s["split"] == "dev"][:pilot_dev_sources])
        print(json.dumps(dict(status="PILOT_ONLY",
                              train_sources=pilot_train_sources,
                              dev_sources=pilot_dev_sources)), flush=True)
    if source_limit is not None:
        if source_limit <= 0:
            raise ValueError("source_limit must be positive")
        sources = sources[:source_limit]
    receipts = []
    for spec in sources:
        for hop in hops:
            receipt = prepare_one(root, spec, hop)
            receipts.append(receipt)
            print(json.dumps(receipt), flush=True)
    return receipts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--hops", type=int, nargs="+", default=list(VALID_HOPS))
    parser.add_argument("--pilot-train-sources", type=int)
    parser.add_argument("--pilot-dev-sources", type=int)
    parser.add_argument("--source-limit", type=int,
                        help="Smoke test ONLY, not a scientifically valid train/dev split")
    args = parser.parse_args()
    prepare(args.root, tuple(args.hops), source_limit=args.source_limit,
            pilot_train_sources=args.pilot_train_sources,
            pilot_dev_sources=args.pilot_dev_sources)


if __name__ == "__main__":
    main()
