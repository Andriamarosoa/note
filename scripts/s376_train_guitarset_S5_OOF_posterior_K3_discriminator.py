"""S376 original GuitarSet K3 third-attack expert with S5 genuinely heldfold posteriors.

All labels and threshold/model selection strictly original GuitarSet train OOF.
Uses original 59,309 native GuitarSet features, 4 original HELDFOLD
S5 posteriors (S259) and original trained risk S18 (S260).
Only original freeze K3 AND ORIGINAL PER-EXAMPLE HELDFOLD S18 K2
are training examples; binary target true K3 vs not K3. Physical
flow, morphology and additional S5 posterior information tested
against compact 118D baseline. Original GuitarSet song members
excluded across train/heldfold. Trained fold f expert gets
source S5 probabilities generated by *that example's original
heldout fold*, not S5 outputs trained on the row.
No IDMT data ever used; strictly NO S80 official promotion.
"""
from __future__ import annotations
import argparse,hashlib,json
from pathlib import Path
import joblib,numpy as np
from sklearn.ensemble import ExtraTreesClassifier
FOLDS=(0,1,2,4);N=59309;SEED=376
AUDIO={'row_id','member','start_samples','end_samples','incumbent_freeze_K',
  'summary58','sequence42x49','flow245','morphology490','physics294',
  'original_PR16_geometry46','geometry3'}
S5={'row_id','incumbent_freeze_K','fold_ids','original_S5_raw_probability_by_fold',
    'original_S5_prior_probability_by_fold','original_S5_K_by_fold','all_four_folds_agree'}
TRUTH={'row_id','true_K','original_fold','original_freeze_K'}
GRID=[round(float(t),3) for t in np.arange(.1,.801,.025)]
def need(ok,msg):
    if not ok:raise ValueError(msg)
def sha(x):return hashlib.sha256(Path(x).read_bytes()).hexdigest()
def load(path,keys):
    with np.load(path,allow_pickle=False) as z:
        need(set(z.files)==keys,'original source schema mismatch '+str(path))
        return {k:z[k].copy() for k in z.files}
def run(audio_path,s5_path,s18_path,truth_path,out):
    need(not out.exists(),'cannot overwrite original source-only training experiment')
    a=load(audio_path,AUDIO); b=load(s5_path,S5);y=load(truth_path,TRUTH)
    with np.load(s18_path,allow_pickle=False) as z:
        need({'row_id','freeze_K','fold_ids','S18_K'}.issubset(z.files),
             'need real historical trained 133 S8-S18 checkpoints')
        ident=z['row_id'].copy();old=z['freeze_K'].copy();s18=z['S18_K'].copy()
        fids=z['fold_ids'].copy()
    ids=a['row_id'];n=len(ids);reference=a['incumbent_freeze_K']
    member=a['member'].astype(str); fold=y['original_fold'].astype(int)
    true=y['true_K'].astype(int)
    need(n==N and all(np.array_equal(ids,x) for x in (b['row_id'],y['row_id'],ident))
         and np.array_equal(reference,b['incumbent_freeze_K'])
         and np.array_equal(reference,y['original_freeze_K'])
         and np.array_equal(reference,old)
         and np.array_equal(fids,FOLDS)
         and np.array_equal(b['fold_ids'],fids)
         and s18.shape==(4,N)
         and b['original_S5_raw_probability_by_fold'].shape==(4,N,7),
         'genuine heldfold source rows not bit-identical')
    by_fold={f:i for i,f in enumerate(FOLDS)}
    ix=np.asarray([by_fold[int(f)] for f in fold],int)
    s18held=s18[ix,np.arange(N)]
    sel=(reference==3)&(s18held==2)
    loc=np.flatnonzero(sel)
    need(len(loc)>=100,'historical true heldfold S18 K3->K2 trigger too rare')
    foldsub=fold[loc];trueclass=true[loc];ys=(trueclass==3).astype(int)
    mm=member[loc]
    raw=b['original_S5_raw_probability_by_fold'][ix[loc],loc,:].astype(np.float32)
    prior=b['original_S5_prior_probability_by_fold'][ix[loc],loc,:].astype(np.float32)
    # Constant geometry and original same-fold OOF S5 posteriors
    base=np.column_stack([a['summary58'][loc],a['original_PR16_geometry46'][loc],
                          raw,prior]).astype(np.float32)
    wide=np.column_stack([base,a['flow245'][loc],a['morphology490'][loc],
                          a['physics294'][loc]]).astype(np.float32)
    need(base.shape==(len(loc),118) and wide.shape==(len(loc),1147)
         and np.isfinite(base).all() and np.isfinite(wide).all(),
         'early source acoustic/posterior feature dimensions invalid')
    out.mkdir(parents=True)
    results={}
    for kind,X in [('source118',base),('source1147',wide)]:
        pred=np.full(len(loc),np.nan,np.float32)
        folds=[]
        for hold in FOLDS:
            val=foldsub==hold
            train=foldsub!=hold
            val_members=set(mm[val])
            source_overlap=len(set(mm[train]).intersection(val_members))
            train &= ~np.isin(mm,list(val_members))
            need(train.sum()>=80 and val.sum()>10
                 and len(np.unique(ys[train]))==2,
                 f'need both classes and >=80 composition-disjoint train groups on fold {hold}')
            clf=ExtraTreesClassifier(n_estimators=192,max_depth=10,
                 min_samples_leaf=3,max_features='sqrt',class_weight='balanced',
                 n_jobs=2,random_state=SEED+hold+
                     (1000 if kind=='source1147' else 0))
            clf.fit(X[train],ys[train])
            pred[val]=clf.predict_proba(X[val])[:,list(clf.classes_).index(1)]
            save=out/f'{kind}_true_original_fold{hold}_K3_expert.joblib'
            joblib.dump(clf,save,compress=3)
            folds.append(dict(fold=hold,train_rows=int(train.sum()),
                validation_rows=int(val.sum()),train_true_K3=int(ys[train].sum()),
                validation_true_K3=int(ys[val].sum()),
                source_member_overlap_detected_excluded=source_overlap,
                source_member_overlap_remaining=0,
                original_source_model_SHA256=sha(save)))
        need(np.isfinite(pred).all() and (pred>=0).all() and (pred<=1).all(),
             'OOF all-fold probabilities missing')
        trials=[]
        for threshold in GRID:
            changed=pred>=threshold
            h=np.bincount(trueclass[changed],minlength=7)
            k3=int(h[3]);reg=int(h.sum()-k3)
            trials.append(dict(threshold=threshold,changed=int(changed.sum()),
                trueK_histogram=h.tolist(),K3_fixes=k3,all_regressions=reg,
                K2_lost=int(h[2]),net=k3-reg,
                eligible_for_external_promotion_gate=bool(k3>=3 and k3>reg and h[2]<=10)))
        results[kind]=dict(feature_width=X.shape[1],source_heldfold_models=folds,
             original_guitarset_trigger_rows=len(loc),
             trigger_true_K_histogram=np.bincount(trueclass,minlength=7).tolist(),
             out_of_fold_threshold_ledger=trials,
             source_audio_and_S5_posterior_OOF_and_group_holdout=True)
        np.savez_compressed(out/f'{kind}_original_GuitarSet_OOF_707_eligible.npz',
            row_id=ids[loc],original_fold=foldsub,original_heldfold_S18_K=s18held[loc],
            posterior_true_K3=pred,reference_K=reference[loc])
    ranked=[(name,t) for name,v in results.items() for t in v['out_of_fold_threshold_ledger']
        if t['eligible_for_external_promotion_gate']]
    ranked.sort(key=lambda it:(-it[1]['net'],it[1]['changed'],-it[1]['threshold'],
                               0 if it[0]=='source118' else 1))
    candidate=None
    if ranked:
        name,t=ranked[0]
        candidate=dict(view=name,threshold=t['threshold'],GuitarSet_development_net=t['net'],
            GuitarSet_development_K3_fixes=t['K3_fixes'],
            GuitarSet_development_regressions=t['all_regressions'],
            GuitarSet_development_K2_lost=t['K2_lost'],
            original_trained_fold_model_SHA256=[x['original_source_model_SHA256']
                                                for x in results[name]['source_heldfold_models']])
    report=dict(status='S376_FOLDHELD_GUITARSET_SOURCE_S5_POSTERIOR_K3_AUDIO_EXPERT',
        original_GuitarSet_N=N,original_true_heldfold_trigger_n=len(loc),
        original_trigger_K2=int(np.count_nonzero(trueclass==2)),
        original_trigger_K3=int(np.count_nonzero(trueclass==3)),
        original_source_audio_SHA256=sha(audio_path),
        original_source_S5_fourfold_SHA256=sha(s5_path),
        original_source_S18_fourfold_SHA256=sha(s18_path),
        original_source_GuitarSet_truth_SHA256=sha(truth_path),
        trained_on_original_GuitarSet_only=True,any_IDMT_WAV_XML_read=False,
        original_outofpiece_group_disjoint_train_validation=True,
        only_one_OOF_S5_heldfold_probability_used_per_original_training_row=True,
        original_frozen_S80_weights_changed=False,
        original_training_only_threshold_grid=GRID,
        original_development_only_outright_no_independent_promotion=True,
        selected_for_truly_unseen_external_S372_8WAV=candidate,
        no_candidate_if_not_better_than_original_heldfold_S18=True,
        sealed_variants=results,official_promotion=False)
    (out/'report.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({k:v for k,v in report.items() if k!='sealed_variants'},indent=2))
    for name,val in results.items():
        print('S376 OLD SOURCE TRAIN ONLY',name,json.dumps([
          dict(threshold=t['threshold'],actions=t['changed'],K3_correct=t['K3_fixes'],
            K2_lost=t['K2_lost'],regressions=t['all_regressions'],
            net=t['net'],pass_gate=t['eligible_for_external_promotion_gate'])
          for t in val['out_of_fold_threshold_ledger']],indent=2))
if __name__=='__main__':
    p=argparse.ArgumentParser()
    for arg in ('audio','s5','s18','truth','out'):
        p.add_argument('--'+arg,type=Path,required=True)
    q=p.parse_args();run(q.audio,q.s5,q.s18,q.truth,q.out)
