"""S266 compatibility wrapper for original frozen 5 rare S45 source models.

Original KMeans cluster fitted on float32 historical reference cannot accept
GuitarSet 59309 receiver float64 generated by NumPy 2.3. This wrapper casts
receiver *to the exact fitted reference dtype*, and does not change the
original checkpoint, threshold, or original provenance-verified source bytes.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import numpy as np
from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler
from scripts import v273_selector_contract as contract
from scripts import recover_v273_missing_s45 as original

def compatible(reference,receiver):
    scaler=StandardScaler().fit(reference)
    a=np.clip(scaler.transform(reference),-6,6)
    b=np.clip(scaler.transform(receiver),-6,6)
    assert a.ndim==b.ndim==2 and a.shape[1]==b.shape[1]
    b=np.asarray(b,dtype=a.dtype)
    cluster=KMeans(n_clusters=3,n_init=10,random_state=contract.SEED)
    return cluster.fit_predict(a),cluster.predict(b)
def test():
    # On identical dtype, the historic unmodified numerical algorithm and
    # this compatibility bridge return the exact same cluster assignments.
    rng=np.random.default_rng(266)
    a=rng.random((150,8)).astype(np.float32)
    b=rng.random((36,8)).astype(np.float32)
    historic=contract.reference_regimes(a,b)
    bridged=compatible(a,b.astype(np.float64))
    assert all(np.array_equal(x,y) for x,y in zip(historic,bridged))
    print("S266 PASS dtype bridge equals original KMeans assignments on float32 reference/float64 receiver")
if __name__=="__main__":
    a=argparse.ArgumentParser()
    for k in ("runtime","historical_proof","external","s5","out"):
        a.add_argument("--"+k.replace("_","-"),dest=k,type=Path,required=True)
    z=a.parse_args()
    test()
    original.reference_regimes=compatible
    original.run(Path("."),z.runtime,z.out,z.external,z.s5,0,False,z.historical_proof)
