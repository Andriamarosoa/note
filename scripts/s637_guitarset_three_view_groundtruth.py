    ("both_060",.60,.60,False,0.),
    ("both_080",.80,.80,False,0.),
    ("both_090",.90,.90,False,0.),
    ("both_080_octave_veto",.80,.80,True,0.),
    ("both_080_octave_veto_K35",.80,.80,True,.35),
