"""S637: *real GuitarSet annotated* 3-window ±octave rescue benchmark.

This is NOT a synthetic-sine or microphone-proposal benchmark. Each GuitarSet
DEV composition is downloaded from the S613 SHA-pinned real-audio manifest;
ground truth annotation comes from the exact same frozen protocol.
No TEST source/labels are opened. Baseline must match historical S614.

Compare S614 exactly versus >1 fixed, causal decision strategies: keep
original native active-K, no fake notes and no future PCM. Reference model
and decoder are never retrained or overwritten.

The three source windows are generated by S634's native 0/x2/half probe.
Only frozen NOTE head inference is deferred in batches of 3x64 feature rows
to avoid per-hop ONNX overhead; time order of selection is unchanged.
"""
