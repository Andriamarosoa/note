"""S96: label-free S45 Ridge risk inference on a new piece.

The original S45 proposal families must be generated by their true source
models. This runtime refuses synthetic/surrogate proposals and cannot
declare end-to-end S80 validation.
"""
from __future__ import annotations
import argparse, json
from pathlib import Path
import joblib
import numpy as np
from scripts.train_v273_s45_specialized_risk_heads import make_inputs

FORBIDDEN={'true_K','truth','label','labels','target','y','correct'}
def predict(proposals_path,features_path,models_dir,output,rule='mean'):
    if output.exists(): raise ValueError('refuse overwrite')
    with np.load(proposals_path,allow_pickle=False) as z:
        if FORBIDDEN.intersection(z.files): raise ValueError('truth forbidden in inference inputs')
        required={'row_id','parent_K','family_ids','proposal_K'}
        if set(z.files)!=required: raise ValueError('proposal contract mismatch')
        a={k:z[k].copy() for k in z.files}
    with np.load(features_path,allow_pickle=False) as z:
        if set(z.files)!={'row_id','acoustic_features'}: raise ValueError('feature contract mismatch')
        ids=z['row_id']; X=z['acoustic_features'].copy()
    old=a['parent_K'].astype(np.int8); cand=a['proposal_K'].astype(np.int8)
    families=list(map(str,a['family_ids'])); n=len(old)
    if not np.array_equal(a['row_id'],ids): raise ValueError('row ID misalignment')
    if len(np.unique(ids))!=n or X.shape[0]!=n or X.shape[1]<139: raise ValueError('feature shape or IDs')
    if cand.shape!=(n,16) or len(families)!=16 or len(set(families))!=16: raise ValueError('16 original families required')
    if not np.isin(cand,range(7)).all() or not np.isin(old,range(7)).all(): raise ValueError('invalid K')
    if not np.isfinite(X[:,:139]).all(): raise ValueError('invalid features')
    changed=cand!=old[:,None]
    votes=np.zeros(cand.shape,np.int16)
    for j in range(16):
        votes[:,j]=(np.sum((cand==cand[:,j,None])&(cand!=old[:,None]),axis=1)-changed[:,j]).astype(np.int16)
    risks=np.full((n,16,2),np.nan,np.float32)
    inventory={}
    for j,family in enumerate(families):
        found=sorted(models_dir.glob('*__'+family+'.joblib'))
        if len(found)!=19: raise ValueError('expected 19 historical piece models for '+family+', got '+str(len(found)))
        idx=np.flatnonzero(changed[:,j])
        scores=[]
        for path in found:
            bundle=joblib.load(path)  # trusted, internally archived checkpoints only
            if bundle.get('family')!=family: raise ValueError('wrong family model')
            if idx.size:
                inputs=make_inputs(X[idx],old[idx],cand[idx,j],votes[idx,j])
                scores.append(np.asarray(bundle['model'].predict(np.clip(bundle['scaler'].transform(inputs),-6,6))))
        if idx.size:
            stack=np.stack(scores)
            if stack.shape!=(19,len(idx),2) or not np.isfinite(stack).all(): raise ValueError('bad model probabilities')
            risks[idx,j]=np.clip(np.mean(stack,axis=0),0,1).astype(np.float32)
        inventory[family]=len(found)
    output.mkdir(parents=True)
    np.savez_compressed(output/'s45_contract.npz',row_id=ids,parent_K=old,
                        family_ids=np.asarray(families),proposal_K=cand,
                        risks=risks,independent_votes=votes)
    result={'status':'S96_EXTERNAL_RISK_CONTRACT_COMPUTED','risk_rule':rule,
            'unseen_piece_model_policy':'mean of all 19 historic held-piece models per family',
            'model_count':sum(inventory.values()),'families':inventory,'event_count':n,
            'truth_read':False,'original_S80_equivalence_proven':False,
            'external_S80_score':None,'promotion':False}
    (output/'report.json').write_text(json.dumps(result,indent=2)+'\n')
    return result

def selftest():
    from scripts.train_v273_s45_specialized_risk_heads import make_inputs
    X=np.zeros((3,335),np.float32); old=np.array([0,2,3],np.int8)
    proposal=np.array([1,3,2],np.int8); votes=np.array([0,1,2],np.int16)
    assert make_inputs(X,old,proposal,votes).shape==(3,156)
    print('S96 PASS: original Ridge feature contract 156D; no synthetic producer or labels')

if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--proposals',type=Path);p.add_argument('--features',type=Path)
    p.add_argument('--models',type=Path);p.add_argument('--output',type=Path)
    p.add_argument('--self-test',action='store_true')
    a=p.parse_args()
    if a.self_test:selftest()
    else:
        if not all((a.proposals,a.features,a.models,a.output)):p.error('all inference inputs required')
        print(json.dumps(predict(a.proposals,a.features,a.models,a.output),indent=2))
